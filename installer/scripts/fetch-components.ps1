# fetch-components.ps1 — CI build step for LULU Remote.
# Run on the Windows CI runner BEFORE Inno Setup, from the repo root:
#   powershell -ExecutionPolicy Bypass -File installer\scripts\fetch-components.ps1
#
# What it does:
#   1. Downloads Moonlight Qt v6.2.0 and Sunshine v2026.914.233613 from
#      their official GitHub releases (asset picked by name via the
#      GitHub releases API — no hardcoded asset URL to go stale).
#   2. Renames them to the canonical names the .iss files expect and
#      writes installer/vendor/MANIFEST.md with version, URL and SHA-256.
#   3. Downloads both projects' LICENSE files into vendor/licenses/
#      (GPL-3.0 requires shipping them; the build FAILS if either is
#      missing — never silently skip this).
#   4. Downloads the Tailscale 1.104.7 MSI ONLY to verify its SHA-256
#      against installer/VERSIONS.md, then deletes it. Tailscale is
#      downloaded at install time, never bundled (see VERSIONS.md).
#
# What it does NOT do: commit anything, upload anything, or touch the
# Flutter build. It only fills installer/vendor/, which is git-ignored.
#
# NOT run yet (no Windows runner here) — first CI run is the test.

param(
    [string]$OutputDir = "$PSScriptRoot\..\vendor",
    [string]$MoonlightVersion = "6.2.0",
    [string]$SunshineVersion = "2026.914.233613",
    # Keep in sync with installer/VERSIONS.md. If Tailscale ever
    # publishes a different file for 1.104.7, this check fails loudly.
    [string]$TailscaleVersion = "1.104.7",
    [string]$TailscaleSha256 = "676b5b32fdd1aeaee90d8e8f38e222635b216fbdfbf877bf01cb1d7cda330ec5"
)

$ErrorActionPreference = 'Stop'

$VendorDir = [System.IO.Path]::GetFullPath($OutputDir)
$LicensesDir = Join-Path $VendorDir 'licenses'
New-Item -ItemType Directory -Force -Path $VendorDir | Out-Null
New-Item -ItemType Directory -Force -Path $LicensesDir | Out-Null

function Get-ReleaseAsset {
    param([string]$Repo, [string]$Tag, [string]$Pattern, [string]$OutFile)
    $api = "https://api.github.com/repos/$Repo/releases/tags/$Tag"
    Write-Host "Looking up $Repo $Tag ..."
    try {
        $headers = @{ 'User-Agent' = 'LULU-Remote-CI' }
        if ($env:GH_TOKEN) { $headers.Authorization = "Bearer $env:GH_TOKEN" }
        $rel = Invoke-RestMethod -Uri $api -Headers $headers
    } catch {
        throw "GitHub releases API failed for $Repo $Tag : $($_.Exception.Message)"
    }
    $asset = $rel.assets | Where-Object { $_.name -like $Pattern } | Select-Object -First 1
    if (-not $asset) {
        $names = ($rel.assets | ForEach-Object { $_.name }) -join ', '
        throw "No asset matching '$Pattern' in $Repo $Tag. Assets on the release: $names"
    }
    Write-Host "Downloading $($asset.name) from $($asset.browser_download_url) ..."
    Invoke-WebRequest -Uri $asset.browser_download_url -OutFile $OutFile -Headers @{ 'User-Agent' = 'LULU-Remote-CI' }
    if ($asset.digest -notmatch '^sha256:([0-9a-f]{64})$' -or (Get-Sha256 $OutFile) -ne $Matches[1]) {
        throw "SHA-256 verification failed for $($asset.name)."
    }
    return $asset
}

function Get-Sha256([string]$Path) {
    return (Get-FileHash -Path $Path -Algorithm SHA256).Hash.ToLower()
}

$manifest = @()
$manifest += '# vendor/MANIFEST.md — generated by installer/scripts/fetch-components.ps1'
$manifest += '# Do not edit by hand. Re-run the script to regenerate.'
$manifest += ''

# --- Moonlight Qt (bundled, GPL-3.0) ---
$moonlightFile = Join-Path $VendorDir 'MoonlightSetup-6.2.0.exe'
$moonlightAsset = Get-ReleaseAsset `
    -Repo 'moonlight-stream/moonlight-qt' `
    -Tag "v$MoonlightVersion" `
    -Pattern 'MoonlightSetup-6.2.0.exe' `
    -OutFile $moonlightFile
$moonlightSha = Get-Sha256 $moonlightFile
$manifest += '## Moonlight Qt'
$manifest += "- Version: v$MoonlightVersion"
$manifest += "- Release asset: $($moonlightAsset.name)"
$manifest += "- Download URL: $($moonlightAsset.browser_download_url)"
$manifest += "- SHA-256: $moonlightSha"
$manifest += '- License: GPL-3.0 — https://github.com/moonlight-stream/moonlight-qt'
$portableZip = Join-Path $VendorDir "MoonlightPortable-x64-$MoonlightVersion.zip"
$portable = Get-ReleaseAsset -Repo 'moonlight-stream/moonlight-qt' `
    -Tag "v$MoonlightVersion" -Pattern "MoonlightPortable-x64-$MoonlightVersion.zip" `
    -OutFile $portableZip
$portableDir = Join-Path $VendorDir 'moonlight'
Expand-Archive -LiteralPath $portableZip -DestinationPath $portableDir -Force
$portableExe = @(Get-ChildItem -LiteralPath $portableDir -Filter Moonlight.exe -File -Recurse)
if ($portableExe.Count -ne 1) { throw 'Unexpected Moonlight portable archive layout.' }
$manifest += "- Portable release asset: $($portable.browser_download_url)"
$manifest += "- Portable SHA-256: $(Get-Sha256 $portableZip)"
$manifest += ''

# --- Sunshine (bundled, GPL-3.0) ---
# The release lives under both LizardByte/Sunshine and SunshineStream/Sunshine
# (org rename); try the old name first, then the new one.
$sunshineFile = Join-Path $VendorDir 'Sunshine-Windows-AMD64-installer.msi'
$sunshineAsset = $null
foreach ($repo in @('LizardByte/Sunshine', 'SunshineStream/Sunshine')) {
    try {
        $sunshineAsset = Get-ReleaseAsset `
            -Repo $repo `
            -Tag "v$SunshineVersion" `
            -Pattern 'Sunshine-Windows-AMD64-installer.msi' `
            -OutFile $sunshineFile
        break
    } catch {
        Write-Host "Sunshine lookup failed on $repo : $($_.Exception.Message)"
    }
}
if (-not $sunshineAsset) {
    throw "Could not download the Sunshine Windows installer from either repo name."
}
$sunshineSha = Get-Sha256 $sunshineFile
$manifest += '## Sunshine'
$manifest += "- Version: v$SunshineVersion"
$manifest += "- Release asset (original name): $($sunshineAsset.name)"
$manifest += "- Saved as: Sunshine-Windows-AMD64-installer.msi"
$manifest += "- Download URL: $($sunshineAsset.browser_download_url)"
$manifest += "- SHA-256: $sunshineSha"
$manifest += '- License: GPL-3.0 — https://github.com/LizardByte/Sunshine'
$manifest += ''

# --- LICENSE texts (required for GPL redistribution — fail if missing) ---
Write-Host 'Downloading LICENSE files ...'
Invoke-WebRequest -Uri 'https://raw.githubusercontent.com/moonlight-stream/moonlight-qt/master/LICENSE' `
    -OutFile (Join-Path $LicensesDir 'Moonlight-LICENSE')
Invoke-WebRequest -Uri 'https://raw.githubusercontent.com/LizardByte/Sunshine/master/LICENSE' `
    -OutFile (Join-Path $LicensesDir 'Sunshine-LICENSE')
foreach ($f in @('Moonlight-LICENSE', 'Sunshine-LICENSE')) {
    $p = Join-Path $LicensesDir $f
    if (-not (Test-Path $p) -or (Get-Item $p).Length -lt 1000) {
        throw "LICENSE download failed or suspiciously small: $p"
    }
}
$manifest += '## License texts shipped in the installers'
$manifest += '- licenses/Moonlight-LICENSE (GPL-3.0, from moonlight-qt master)'
$manifest += '- licenses/Sunshine-LICENSE (GPL-3.0, from Sunshine master)'
$manifest += '- installer/licenses/MOONLIGHT-SOURCE-OFFER.txt'
$manifest += '- installer/licenses/SUNSHINE-SOURCE-OFFER.txt'
$manifest += ''

# --- Tailscale (NOT bundled — verify only, then delete) ---
$tailscaleUrl = "https://pkgs.tailscale.com/stable/tailscale-setup-$TailscaleVersion-amd64.msi"
$tailscaleTmp = Join-Path $env:TEMP "tailscale-setup-$TailscaleVersion-amd64.msi"
Write-Host "Verifying Tailscale $TailscaleVersion (download only, will delete) ..."
Invoke-WebRequest -Uri $tailscaleUrl -OutFile $tailscaleTmp
$tailscaleSha = Get-Sha256 $tailscaleTmp
Remove-Item $tailscaleTmp -Force
if ($tailscaleSha -ne $TailscaleSha256.ToLower()) {
    throw "Tailscale SHA-256 mismatch! Expected $TailscaleSha256, got $tailscaleSha. " +
          "Do NOT ship this build — update installer/VERSIONS.md first."
}
$manifest += '## Tailscale (downloaded at install time, NOT bundled)'
$manifest += "- Version: $TailscaleVersion"
$manifest += "- Download URL: $tailscaleUrl"
$manifest += "- SHA-256 (verified at build time): $tailscaleSha"
$manifest += '- License: BSD-3-Clause — https://github.com/tailscale/tailscale'
$manifest += ''

$manifest | Set-Content -Path (Join-Path $VendorDir 'MANIFEST.md') -Encoding UTF8
Write-Host ''
Write-Host 'Done. vendor/ now contains:'
Get-ChildItem $VendorDir -Recurse -File | ForEach-Object { Write-Host "  $($_.FullName)" }
